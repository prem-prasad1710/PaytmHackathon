"""Synthetic UPI world simulator.

Produces a time-ordered event log (account creations, payments, complaints, blocks).
No real customer data is used. The log is NOT a table of random numbers: it is
generated by agents with behaviour, and fraud labels come from the campaign that
generated a payment, never from the features.

Legitimate world
  * ~6k users with stable devices/IPs, home hours, personal amount scales and a small
    set of frequent recipients (merchants + friends); 12% of payments go to new recipients.
  * Hard negatives that look suspicious but are fine: flash-sale merchants and viral new
    accounts with big payment bursts, genuine phone upgrades (new device + new IP), shopping
    sprees, large one-off payments (rent), family-shared devices, kiosks, carrier-NAT IPs,
    and routine dispute complaints against honest merchants.

Fraud campaigns (each is a ring of freshly created recipient accounts, with shared infra)
  phishing_kyc     small repeated "verification" amounts, bursty waves, many victims
  reward_scam      small repeated "processing fees", concentrated on one account
  investment_scam  each victim pays repeatedly with escalating amounts, money moves on fast
  job_scam         repeated similar small/medium "task fees" from the same victims
  account_takeover attacker devices/IPs, night-time sessions, bursts of large transfers to mules
  money_mule       older recruited accounts receiving from many strangers and forwarding in minutes

Victims complain with delay; accounts are blocked once enough complaints land, and
blocks propagate to ring-mates. After a block most scam traffic stops (a few stragglers
remain), exactly the feedback loop a real platform would show.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Optional

import numpy as np

IST = 19800
DAY = 86400.0
START_TS = datetime(2026, 1, 1, tzinfo=timezone.utc).timestamp() - IST

SCAM_TYPES = ["phishing_kyc", "reward_scam", "investment_scam", "job_scam", "account_takeover", "money_mule"]
BLOCK_THRESHOLD = 4
EVENT_ORDER = {"account_created": 0, "transaction": 1, "complaint": 2, "block": 3}


@dataclass
class SimConfig:
    seed: int = 42
    days: int = 60
    n_users: int = 6000
    n_merchants: int = 1200
    n_new_legit: int = 2500
    target_legit_txns: int = 104_000
    campaigns: Dict[str, int] = field(default_factory=lambda: {
        "phishing_kyc": 20, "reward_scam": 14, "investment_scam": 12,
        "job_scam": 16, "account_takeover": 18, "money_mule": 8,
    })

    @property
    def end_ts(self) -> float:
        return START_TS + self.days * DAY


class WorldSimulator:
    def __init__(self, config: Optional[SimConfig] = None):
        self.cfg = config or SimConfig()
        self.rng = np.random.default_rng(self.cfg.seed)
        self.events: List[dict] = []
        self.users: List[dict] = []
        self.merchants: List[dict] = []
        self.new_legit: List[dict] = []
        self.past_rings: List[dict] = []
        self.nat_ips = [f"IP_NAT{k:02d}" for k in range(20)]
        self.shared_ips: List[str] = []
        self.campaign_counter = 0
        self.stealth = 0.0
        self.new_legit_cum: np.ndarray = np.array([])

    # ------------------------------------------------------------------ small helpers
    def _pick(self, seq):
        return seq[int(self.rng.integers(len(seq)))]

    def _account(self, account_id: str, created_ts: float, device: str, ip: str) -> dict:
        acct = {"id": account_id, "created_ts": created_ts, "device": device, "ip": ip}
        self.events.append({"type": "account_created", "ts": created_ts, "account_id": account_id,
                            "device_id": device, "ip_id": ip})
        return acct

    def _tx(self, ts: float, sender: str, recipient: str, amount: float, device: str, ip: str,
            fraud: int = 0, scam_type: str = "legit") -> None:
        if ts >= self.cfg.end_ts or ts < START_TS:
            return
        self.events.append({
            "type": "transaction", "ts": float(ts), "sender_id": sender, "recipient_id": recipient,
            "amount": float(max(1.0, round(amount))), "device_id": device, "ip_id": ip,
            "is_fraud": fraud, "scam_type": scam_type,
        })

    def _user_infra(self, user: dict, ts: float):
        if user["change_ts"] is not None and ts >= user["change_ts"]:
            return user["device_new"], user["ip_new"]
        return user["device"], user["ip"]

    # ------------------------------------------------------------------ legitimate population
    def _build_population(self) -> None:
        rng, cfg = self.rng, self.cfg
        kiosks = [f"D_KIOSK{k:02d}" for k in range(15)]
        shared_ips = self.shared_ips = [f"IP_S{k:03d}" for k in range(500)]

        for j in range(cfg.n_merchants):
            age = rng.uniform(150, 2000)
            m = self._account(f"M{j:04d}", START_TS - age * DAY, f"D_M{j:04d}", f"IP_M{j:04d}")
            self.merchants.append(m)

        for k in range(cfg.n_new_legit):
            created = START_TS + rng.uniform(-6, cfg.days - 4) * DAY
            self.new_legit.append(self._account(f"N{k:04d}", created, f"D_N{k:04d}", f"IP_N{k:04d}"))

        self.new_legit_cum = np.cumsum(1.0 / (np.arange(cfg.n_new_legit) + 1.0) ** 0.8)
        rates = rng.lognormal(0.0, 0.8, cfg.n_users)
        rates *= cfg.target_legit_txns / cfg.days / rates.sum()

        for i in range(cfg.n_users):
            age = rng.uniform(1, 20) if rng.random() < 0.04 else math.exp(rng.uniform(math.log(20), math.log(1800)))
            if i > 0 and rng.random() < 0.12:
                device, ip = self.users[i - 1]["device"], self.users[i - 1]["ip"]
            else:
                device = self._pick(kiosks) if rng.random() < 0.04 else f"D_U{i:05d}"
                r = rng.random()
                ip = self._pick(self.nat_ips) if r < 0.08 else (self._pick(shared_ips) if r < 0.38 else f"IP_U{i:05d}")
            user = self._account(f"U{i:05d}", START_TS - age * DAY, device, ip)
            user.update({
                "rate": float(rates[i]),
                "mu": float(rng.normal(6.0, 0.8)),
                "sigma": float(rng.uniform(0.4, 0.8)),
                "peak": float(np.clip(rng.normal(15, 4), 8, 22)),
                "change_ts": START_TS + rng.uniform(5, cfg.days - 3) * DAY if rng.random() < 0.12 else None,
                "device_new": f"D_U{i:05d}_n",
                "ip_new": f"IP_U{i:05d}_n",
            })
            self.users.append(user)

        weights = 1.0 / (np.arange(cfg.n_merchants) + 1.0) ** 0.7
        weights /= weights.sum()
        for user in self.users:
            n_c = int(rng.integers(3, 11))
            n_m = max(1, round(n_c * 0.55))
            ms = rng.choice(cfg.n_merchants, size=n_m, replace=False, p=weights)
            us = rng.choice(cfg.n_users, size=n_c - n_m, replace=False)
            contacts = [self.merchants[int(j)]["id"] for j in ms] + [self.users[int(j)]["id"] for j in us if self.users[int(j)]["id"] != user["id"]]
            rng.shuffle(contacts)
            w = 0.65 ** np.arange(len(contacts))
            user["contacts"], user["contact_w"] = contacts, w / w.sum()

    def _new_recipient(self) -> dict:
        r = self.rng.random()
        if r < 0.32:
            return self._pick(self.merchants)
        if r < 0.67:
            return self._pick(self.users)
        idx = int(np.searchsorted(self.new_legit_cum, self.rng.random() * self.new_legit_cum[-1]))
        return self.new_legit[min(idx, len(self.new_legit) - 1)]

    def _generate_legit(self) -> None:
        rng, cfg = self.rng, self.cfg
        by_id = {a["id"]: a for a in self.merchants + self.users + self.new_legit}
        for user in self.users:
            n = int(rng.poisson(user["rate"] * cfg.days))
            if n == 0:
                continue
            day = rng.integers(0, cfg.days, n)
            night = rng.random(n) < 0.04
            hour = np.where(night, rng.integers(0, 24, n), np.round(rng.normal(user["peak"], 3.5, n)).astype(int) % 24)
            ts = START_TS + day * DAY + hour * 3600 + rng.integers(0, 3600, n)
            amount = np.exp(rng.normal(user["mu"], user["sigma"], n))
            amount = np.where(rng.random(n) < 0.02, amount * rng.uniform(5, 12, n), amount)
            amount = np.where((amount > 100) & (rng.random(n) < 0.5), np.round(amount / 10) * 10, amount)
            is_new = rng.random(n) < 0.12
            idx = rng.choice(len(user["contacts"]), size=n, p=user["contact_w"])
            for k in range(n):
                t = float(ts[k])
                if is_new[k]:
                    rec = self._new_recipient()
                    if rec["id"] == user["id"]:
                        continue
                    t = max(t, rec["created_ts"] + rng.uniform(1, 48) * 3600)
                else:
                    rec = by_id[user["contacts"][int(idx[k])]]
                dev, ip = self._user_infra(user, t)
                self._tx(t, user["id"], rec["id"], float(amount[k]), dev, ip)
                if rng.random() < 0.03:
                    for _ in range(int(rng.integers(1, 4))):
                        t2 = t + rng.uniform(60, 2400)
                        m = self._pick(self.merchants)
                        dev2, ip2 = self._user_infra(user, t2)
                        self._tx(t2, user["id"], m["id"], float(np.exp(rng.normal(user["mu"], user["sigma"]))), dev2, ip2)

    def _generate_legit_bursts(self) -> None:
        rng, cfg = self.rng, self.cfg
        targets = [self._pick(self.merchants) for _ in range(10)]
        targets += [self.new_legit[int(i)] for i in rng.choice(len(self.new_legit), 6, replace=False)]
        for target in targets:
            earliest = max(2.0, (target["created_ts"] - START_TS) / DAY + 0.5)
            day = rng.uniform(earliest, cfg.days - 2)
            start = START_TS + day * DAY + rng.uniform(11, 20) * 3600
            n = int(rng.integers(80, 320))
            span = rng.uniform(1, 3) * 3600 if target["id"].startswith("M") else rng.uniform(0.4, 1.5) * 3600
            for _ in range(n):
                u = self._pick(self.users)
                t = start + rng.uniform(0, span)
                dev, ip = self._user_infra(u, t)
                self._tx(t, u["id"], target["id"], float(np.exp(rng.normal(5.3, 0.5))), dev, ip)

    def _generate_donation_drives(self) -> None:
        """Legitimate look-alikes of phishing/reward scams: brand-new accounts that collect
        many identical small payments in a short burst (festival collections, new shops)."""
        rng, cfg = self.rng, self.cfg
        for k in range(14):
            created = START_TS + rng.uniform(2, cfg.days - 4) * DAY
            drive = self._account(f"DR{k:03d}", created - rng.uniform(0.5, 20) * DAY, f"D_DR{k:03d}", f"IP_DR{k:03d}")
            canonical = self._pick([11, 21, 51, 101, 201, 501])
            starts = [created + rng.uniform(0, 36) * 3600 for _ in range(int(rng.integers(1, 4)))]
            for _ in range(int(rng.integers(40, 181))):
                u = self._pick(self.users)
                t = self._pick(starts) + rng.uniform(0, 1800)
                dev, ip = self._user_infra(u, t)
                amount = canonical if rng.random() < 0.8 else self._pick([11, 21, 51, 101, 201, 501])
                self._tx(t, u["id"], drive["id"], amount, dev, ip)

    def _generate_legit_complaints(self) -> None:
        rng = self.rng
        for ev in list(self.events):
            if ev["type"] == "transaction" and rng.random() < 0.0025:
                self.events.append({"type": "complaint", "ts": ev["ts"] + rng.exponential(10 * 3600) + 600,
                                    "account_id": ev["recipient_id"], "reporter_id": ev["sender_id"]})

    # ------------------------------------------------------------------ fraud campaigns
    def _ring_infra(self, cid: int, t0: float) -> dict:
        rng = self.rng
        stealth = rng.random() < 0.2
        devices = [f"D_R{cid}_{k}" for k in range(int(rng.integers(1, 3)))]
        reusable = [r for r in self.past_rings if r["block_ts"] is not None and r["block_ts"] < t0 - DAY]
        if reusable and rng.random() < 0.3:
            devices.append(self._pick(self._pick(reusable)["devices"]))
        r = rng.random()
        if r < 0.3:
            ips = [self._pick(self.nat_ips)]
        elif r < 0.5:
            ips = [self._pick(self.shared_ips)]
        else:
            ips = [f"IP_R{cid}_{k}" for k in range(int(rng.integers(1, 3)))]
        return {"devices": devices, "ips": ips, "share_prob": 0.0 if stealth else 0.75}

    def _scam_accounts(self, cid: int, prefix: str, n: int, age_lo: float, age_hi: float, t0: float, infra: dict) -> List[dict]:
        rng, out = self.rng, []
        for k in range(n):
            share = rng.random() < infra["share_prob"]
            device = self._pick(infra["devices"]) if share else f"D_{prefix}{cid}_{k}"
            ip = self._pick(infra["ips"]) if share else f"IP_{prefix}{cid}_{k}"
            age = rng.uniform(30, 300) if (prefix != "COL" and rng.random() < 0.15 + 0.35 * self.stealth) else rng.uniform(age_lo, age_hi)
            acct = self._account(f"{prefix}{cid}_{k}", t0 - age * DAY, device, ip)
            acct["shared"] = share
            out.append(acct)
            window_start = max(acct["created_ts"], t0 - 40 * DAY)
            if prefix not in ("COL", "SA") and rng.random() < 0.15 + 0.5 * self.stealth and t0 - window_start > 2 * DAY:
                for _ in range(int(rng.integers(3, 26))):
                    u = self._pick(self.users)
                    t = rng.uniform(window_start, t0)
                    dev, ip = self._user_infra(u, t)
                    self._tx(t, u["id"], acct["id"], math.exp(rng.normal(u["mu"], u["sigma"])), dev, ip)
        return out

    def _finalize_campaign(self, scam_type: str, accounts: List[dict], arrivals: List[dict], infra: dict,
                           p_complain: float, delay_hours: float, p_forward: float, cid: int) -> None:
        rng, end = self.rng, self.cfg.end_ts
        state = {a["id"]: {"c": [], "blocked": None, "never": rng.random() < 0.12} for a in accounts}
        collectors = []
        if p_forward > 0:
            collectors = self._scam_accounts(cid, "COL", int(rng.integers(1, 4)), 3, 40,
                                             min(a["ts"] for a in arrivals) if arrivals else START_TS, {
                                                 "devices": [f"D_COL{cid}"], "ips": [f"IP_COL{cid}"], "share_prob": 0.5})

        kept = []
        for arr in sorted(arrivals, key=lambda a: a["ts"]):
            st = state[arr["recipient"]]
            if arr["ts"] >= end:
                continue
            if st["blocked"] is not None and arr["ts"] > st["blocked"] and rng.random() > 0.06:
                continue
            kept.append(arr)
            if rng.random() < p_complain:
                st["c"].append((arr["ts"] + rng.exponential(delay_hours * 3600) + 120, arr["sender"]))
                if len(st["c"]) >= BLOCK_THRESHOLD and st["blocked"] is None and not st["never"]:
                    cts = sorted(c for c, _ in st["c"])
                    st["blocked"] = cts[BLOCK_THRESHOLD - 1] + rng.exponential(2 * 3600) + 1800
                    for sib in accounts:
                        if sib["id"] != arr["recipient"] and (sib["shared"] or rng.random() < 0.3) and rng.random() < 0.6:
                            s2 = state[sib["id"]]
                            cand = st["blocked"] + rng.exponential(3 * 3600) + 600
                            if s2["blocked"] is None or cand < s2["blocked"]:
                                s2["blocked"] = cand

        by_id = {a["id"]: a for a in accounts}
        for arr in kept:
            self._tx(arr["ts"], arr["sender"], arr["recipient"], arr["amount"], arr["device"], arr["ip"], 1, scam_type)
            if collectors and rng.random() < p_forward:
                src = by_id[arr["recipient"]]
                t_fwd = arr["ts"] + float(np.clip(rng.lognormal(math.log(480), 0.8), 60, 2400))
                blocked = state[src["id"]]["blocked"]
                if blocked is None or t_fwd < blocked:
                    col = self._pick(collectors)
                    self._tx(t_fwd, src["id"], col["id"], arr["amount"] * rng.uniform(0.85, 0.98),
                             src["device"], src["ip"], 1, "money_mule")

        first_blocks = []
        for acct_id, st in state.items():
            for c_ts, reporter in st["c"]:
                if c_ts < end:
                    self.events.append({"type": "complaint", "ts": c_ts, "account_id": acct_id, "reporter_id": reporter})
            if st["blocked"] is not None and st["blocked"] < end:
                self.events.append({"type": "block", "ts": st["blocked"], "account_id": acct_id})
                first_blocks.append(st["blocked"])
        if first_blocks and collectors:
            for col in collectors:
                if rng.random() < 0.5:
                    self.events.append({"type": "block", "ts": max(first_blocks) + rng.exponential(6 * 3600) + 600,
                                        "account_id": col["id"]})
        self.past_rings.append({"devices": infra["devices"], "block_ts": min(first_blocks) if first_blocks else None})

    def _waking(self, ts: float) -> float:
        hour = ((ts - START_TS) % DAY) / 3600
        return ts + (7 - hour) * 3600 + self.rng.uniform(0, 3 * 3600) if hour < 7 else ts

    def _victim_arrival(self, ts: float, victim: dict, recipient: dict, amount: float) -> dict:
        ts = self._waking(ts)
        if amount < 5000 and self.rng.random() < 0.5 * self.stealth:
            amount = math.exp(victim["mu"] + self.rng.normal(0, 0.3))
        dev, ip = self._user_infra(victim, ts)
        return {"ts": ts, "sender": victim["id"], "recipient": recipient["id"], "amount": amount, "device": dev, "ip": ip}

    def _weighted(self, accounts: List[dict], concentrate: float = 0.0) -> dict:
        if concentrate and self.rng.random() < concentrate:
            return accounts[0]
        return self._pick(accounts)

    def _campaign_phishing(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        accounts = self._scam_accounts(cid, "SP", int(rng.integers(1, 5)), 0, 10, t0, infra)
        canonical = self._pick([1, 2, 5, 10, 11, 21, 49, 99, 149, 199])
        spread = 36 * 3600 * (1 + 6 * self.stealth)
        wave_starts = [t0 + rng.uniform(0, spread) for _ in range(int(rng.integers(2, 7)))]
        wave_acct = [self._pick(accounts) for _ in wave_starts]
        arrivals = []
        for victim in rng.choice(self.users, size=int(rng.integers(50, 251)), replace=False):
            if rng.random() < 0.55 * (1 - self.stealth):
                w = int(rng.integers(len(wave_starts)))
                ts, rec = wave_starts[w] + rng.uniform(0, 420), (wave_acct[w] if rng.random() < 0.8 else self._pick(accounts))
            else:
                ts, rec = t0 + rng.uniform(0, spread), self._pick(accounts)
            amount = canonical if rng.random() < 0.7 else self._pick([1, 2, 5, 10, 11, 21, 49, 99, 149, 199])
            arrivals.append(self._victim_arrival(ts, victim, rec, amount))
        self._finalize_campaign("phishing_kyc", accounts, arrivals, infra, 0.30, 6, 0.12, cid)

    def _campaign_reward(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        accounts = self._scam_accounts(cid, "SR", int(rng.integers(1, 4)), 0, 15, t0, infra)
        canonical = self._pick([99, 149, 199, 299, 499])
        spread = 72 * 3600 * (1 + 4 * self.stealth)
        bursts = [t0 + rng.uniform(0, spread) for _ in range(int(rng.integers(1, 3)))]
        arrivals = []
        for victim in rng.choice(self.users, size=int(rng.integers(30, 141)), replace=False):
            ts = (self._pick(bursts) + rng.uniform(0, 600)) if rng.random() < 0.25 * (1 - self.stealth) else t0 + rng.uniform(0, spread)
            rec = self._weighted(accounts, 0.75)
            amount = canonical if rng.random() < 0.8 else self._pick([99, 149, 199, 299, 499])
            arrivals.append(self._victim_arrival(ts, victim, rec, amount))
            if rng.random() < 0.10:
                arrivals.append(self._victim_arrival(ts + rng.uniform(600, 6 * 3600), victim, rec, amount))
        self._finalize_campaign("reward_scam", accounts, arrivals, infra, 0.25, 8, 0.10, cid)

    def _campaign_investment(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        accounts = self._scam_accounts(cid, "SI", int(rng.integers(1, 4)), 7, 60, t0, infra)
        arrivals = []
        for victim in rng.choice(self.users, size=int(rng.integers(12, 61)), replace=False):
            rec = self._pick(accounts)
            amt = self._pick([2000, 5000, 10000, 20000]) * rng.uniform(0.7, 1.5)
            mult, ts = rng.uniform(1.4, 3.0), t0 + rng.uniform(0, 5 * DAY * (1 + 2 * self.stealth))
            for _ in range(int(rng.integers(2, 6))):
                arrivals.append(self._victim_arrival(ts, victim, rec, round(amt, -2)))
                amt, ts = min(amt * mult, 800_000), ts + rng.uniform(0.3, 3) * DAY
        self._finalize_campaign("investment_scam", accounts, arrivals, infra, 0.22, 20, 0.5, cid)

    def _campaign_job(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        accounts = self._scam_accounts(cid, "SJ", int(rng.integers(1, 4)), 2, 25, t0, infra)
        arrivals = []
        for victim in rng.choice(self.users, size=int(rng.integers(20, 71)), replace=False):
            rec = self._pick(accounts)
            base, ts = self._pick([500, 1000, 1500, 2000, 3000]), t0 + rng.uniform(0, 4 * DAY * (1 + 3 * self.stealth))
            for _ in range(int(rng.integers(2, 5))):
                arrivals.append(self._victim_arrival(ts, victim, rec, base * rng.uniform(0.95, 1.1)))
                ts += rng.uniform(0.1, 2) * DAY
        self._finalize_campaign("job_scam", accounts, arrivals, infra, 0.25, 12, 0.2, cid)

    def _campaign_takeover(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        mules = self._scam_accounts(cid, "SA", int(rng.integers(3, 9)), 0, 20, t0, infra)
        att_dev = [f"D_ATO{cid}_{k}" for k in range(int(rng.integers(2, 7)))]
        att_ip = [f"IP_ATO{cid}_{k}" for k in range(int(rng.integers(2, 7)))]
        arrivals = []
        for victim in rng.choice(self.users, size=int(rng.integers(12, 36)), replace=False):
            day = t0 + rng.uniform(0, 8) * DAY
            if rng.random() < 0.7:
                day = math.floor((day - START_TS) / DAY) * DAY + START_TS + rng.uniform(0, 5) * 3600
            targets = [self._pick(mules) for _ in range(int(rng.integers(1, 4)))]
            dev, ip, ts = self._pick(att_dev), self._pick(att_ip), day
            typical = math.exp(victim["mu"])
            for _ in range(int(rng.integers(2, 8))):
                amount = min(typical * rng.uniform(3, 8), 60_000) if rng.random() < 0.6 else rng.uniform(3000, 60_000)
                arrivals.append({"ts": ts, "sender": victim["id"], "recipient": self._pick(targets)["id"],
                                 "amount": amount, "device": dev, "ip": ip})
                ts += rng.uniform(60, 360)
        self._finalize_campaign("account_takeover", mules, arrivals, infra, 0.7, 4, 0.4, cid)

    def _campaign_mule(self, cid: int, t0: float) -> None:
        rng = self.rng
        infra = self._ring_infra(cid, t0)
        mules = self._scam_accounts(cid, "SM", int(rng.integers(2, 6)), 15, 200, t0, infra)
        arrivals = []
        for mule in mules:
            for victim in rng.choice(self.users, size=int(rng.integers(20, 61)), replace=False):
                arrivals.append(self._victim_arrival(t0 + rng.uniform(0, 5 * DAY * (1 + 2 * self.stealth)), victim, mule,
                                                     math.exp(rng.normal(math.log(4000), 0.7))))
        self._finalize_campaign("money_mule", mules, arrivals, infra, 0.18, 24, 1.0, cid)

    def _generate_campaigns(self) -> None:
        rng, cfg = self.rng, self.cfg
        runners = {
            "phishing_kyc": self._campaign_phishing, "reward_scam": self._campaign_reward,
            "investment_scam": self._campaign_investment, "job_scam": self._campaign_job,
            "account_takeover": self._campaign_takeover, "money_mule": self._campaign_mule,
        }
        schedule = []
        for kind, count in cfg.campaigns.items():
            span = cfg.days - 7
            slot = span / count
            for i in range(count):
                day = 2 + i * slot + rng.uniform(0, slot * 0.9)
                schedule.append((START_TS + day * DAY + rng.uniform(0, DAY), kind))
        for t0, kind in sorted(schedule):
            self.campaign_counter += 1
            self.stealth = float(rng.beta(2, 3))
            runners[kind](self.campaign_counter, t0)

    # ------------------------------------------------------------------ public API
    def generate(self) -> List[dict]:
        self._build_population()
        self._generate_legit()
        self._generate_legit_bursts()
        self._generate_donation_drives()
        self._generate_legit_complaints()
        self._generate_campaigns()
        self.events.sort(key=lambda e: (e["ts"], EVENT_ORDER[e["type"]]))
        n = 0
        for ev in self.events:
            if ev["type"] == "transaction":
                n += 1
                ev["transaction_id"] = f"TX{n:07d}"
        return self.events


def generate_events(config: Optional[SimConfig] = None) -> List[dict]:
    return WorldSimulator(config).generate()
